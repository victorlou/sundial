// The entities the recurrence engine reads (domain model §2.5–§2.8). Storage-only fields
// (timestamps, `deletedAt`, the scope copies on rule versions and actions, server-set fields) stay in Data.

/// Who a task belongs to (DM-15).
public enum Scope: Hashable, Sendable {
    case personal(ProfileID)
    case household(HouseholdID)
}

/// Domain model §2.5.
public struct Slot: Hashable, Sendable {
    public var id: SlotID
    public var householdId: HouseholdID
    public var name: String
    public var sortOrder: Int
    /// Exactly one per household. It always sorts last.
    public var isAnytime: Bool
    public var isArchived: Bool

    public init(id: SlotID, householdId: HouseholdID, name: String, sortOrder: Int, isAnytime: Bool = false, isArchived: Bool = false) {
        self.id = id
        self.householdId = householdId
        self.name = name
        self.sortOrder = sortOrder
        self.isAnytime = isAnytime
        self.isArchived = isArchived
    }
}

/// The domain model's Task (§2.6), named so it doesn't shadow Swift's `Task`.
public struct TaskDefinition: Hashable, Sendable {
    public var id: TaskID
    public var scope: Scope
    public var title: String
    public var notes: String?
    public var icon: String?
    public var points: Int
    public var createdByProfileId: ProfileID
    /// Archived tasks are hidden, and their history is kept.
    public var isArchived: Bool

    public init(
        id: TaskID, scope: Scope, title: String, notes: String? = nil, icon: String? = nil, points: Int = 0,
        createdByProfileId: ProfileID, isArchived: Bool = false
    ) {
        self.id = id
        self.scope = scope
        self.title = title
        self.notes = notes
        self.icon = icon
        self.points = points
        self.createdByProfileId = createdByProfileId
        self.isArchived = isArchived
    }
}

public enum Anchor: Hashable, Sendable {
    case fixed
    case floating
}

public enum MissPolicy: Hashable, Sendable {
    case vanish
    case markMissed
    case carryOver
}

public enum WeekdayOrdinal: Hashable, Sendable {
    case first, second, third, fourth, last
}

/// Which day of the month a `months` pattern lands on.
public enum MonthDay: Hashable, Sendable {
    /// Day k, clamped to the month's length (DM-06).
    case day(Int)
    /// "The 1st/2nd/3rd/4th/last Sat".
    case weekday(WeekdayOrdinal, Weekday)
}

/// Domain model §5.1. `start` belongs to the pattern, not the version.
/// Floating versions use only `every`: their weekdays are empty and their month day is nil.
public enum Pattern: Hashable, Sendable {
    /// Due on `date`. Undated: due on the version's `effectiveFrom`, or the start of its run of undated `once` versions.
    case once(date: LogicalDate?)
    case days(every: Int, start: LogicalDate)
    /// Weeks run Sunday to Saturday.
    case weeks(every: Int, on: Set<Weekday>, start: LogicalDate)
    case months(every: Int, on: MonthDay?, start: LogicalDate)
}

/// DM-02.
public enum Assignment: Hashable, Sendable {
    /// Implicitly the owner of a personal task.
    case personal
    case each([ProfileID])
    case anyOf([ProfileID])
}

/// Domain model §2.7. The version in effect on a date is the one with the greatest `effectiveFrom` on or before it.
public struct RuleVersion: Hashable, Sendable {
    /// UUIDv5(taskId, effectiveFrom), generated by Data.
    public var id: RuleVersionID
    public var taskId: TaskID
    public var effectiveFrom: LogicalDate
    public var anchor: Anchor
    public var pattern: Pattern
    public var slotIds: [SlotID]
    /// Only on a remap version: old slot → new slot (§5.10).
    public var slotMap: [SlotID: SlotID]?
    public var missPolicy: MissPolicy
    public var assignment: Assignment
    /// The first due date of a floating lane with no history.
    public var floatingSeed: LogicalDate?

    public init(
        id: RuleVersionID, taskId: TaskID, effectiveFrom: LogicalDate, anchor: Anchor, pattern: Pattern, slotIds: [SlotID],
        slotMap: [SlotID: SlotID]? = nil, missPolicy: MissPolicy, assignment: Assignment, floatingSeed: LogicalDate? = nil
    ) {
        self.id = id
        self.taskId = taskId
        self.effectiveFrom = effectiveFrom
        self.anchor = anchor
        self.pattern = pattern
        self.slotIds = slotIds
        self.slotMap = slotMap
        self.missPolicy = missPolicy
        self.assignment = assignment
        self.floatingSeed = floatingSeed
    }
}

public enum ActionKind: Hashable, Sendable {
    case complete
    case skip
    case snooze

    /// `complete` and `skip` resolve an occurrence; `snooze` only hides it.
    public var isResolving: Bool { self != .snooze }
}

/// Domain model §2.8. Append-only; undo sets `isRevoked`.
public struct OccurrenceAction: Hashable, Sendable {
    public var id: ActionID
    public var taskId: TaskID
    public var kind: ActionKind
    public var slotId: SlotID
    /// Nil for `anyOf` lanes.
    public var assigneeProfileId: ProfileID?
    /// Which occurrence the action targets.
    public var occurrenceDate: LogicalDate
    /// The day it counts for: when it was done (complete), the day the floating clock restarts from (skip),
    /// or the day it was snoozed (snooze).
    public var actedOn: LogicalDate
    public var actorProfileId: ProfileID
    public var snoozeUntil: LogicalDate?
    /// `revokedAt` is set.
    public var isRevoked: Bool

    public init(
        id: ActionID, taskId: TaskID, kind: ActionKind, slotId: SlotID, assigneeProfileId: ProfileID?,
        occurrenceDate: LogicalDate, actedOn: LogicalDate, actorProfileId: ProfileID, snoozeUntil: LogicalDate? = nil,
        isRevoked: Bool = false
    ) {
        self.id = id
        self.taskId = taskId
        self.kind = kind
        self.slotId = slotId
        self.assigneeProfileId = assigneeProfileId
        self.occurrenceDate = occurrenceDate
        self.actedOn = actedOn
        self.actorProfileId = actorProfileId
        self.snoozeUntil = snoozeUntil
        self.isRevoked = isRevoked
    }
}

/// Everything the engine needs about one task: the task, all its rule versions, and all its actions.
public struct TaskRecord: Hashable, Sendable {
    public var task: TaskDefinition
    public var versions: [RuleVersion]
    public var actions: [OccurrenceAction]

    public init(task: TaskDefinition, versions: [RuleVersion], actions: [OccurrenceAction]) {
        self.task = task
        self.versions = versions
        self.actions = actions
    }
}
